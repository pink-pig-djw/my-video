"""Foot-locked ground tracks for the walk cycles: how far the body must move between walk frames so that the planted
shoe stays fixed on the ground (as the game's reanim _ground track does).

  uv run --no-project --with pillow --with numpy --with scipy python tools/footlock.py [anim ...]

For every frame of the atlas (assets/anim/<anim>.png, frames from src/data/anims.js): the two shoes are found (brown
pixels in the lowest 15% of the figure, split into blobs), each shoe's x relative to the frame anchor and its lowest y.
Between frame i and i+1 the shoe that is on the ground (lowest) in both frames is followed; the body advance is how far
that shoe slid backwards relative to the body. Writes ANIMS[anim].ground = cumulative advance in logical units
(length n + 1; ground[n] = one whole cycle) into src/data/anims.js, and a check plot render/review/footlock_<anim>.png.
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
AP = ROOT / 'src' / 'data' / 'anims.js'
t = AP.read_text(encoding='utf-8'); ANIMS = json.loads(t[t.index('{'):t.rindex('}') + 1])


def shoes(cell, ax, ay):
    a = np.asarray(cell).astype(np.float32)
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    on = al > 128
    ys, xs = np.nonzero(on)
    top, bottom = ys.min(), ys.max()
    band = np.zeros_like(on); band[int(bottom - (bottom - top) * 0.15):] = True
    shoe = on & band & (r > 60) & (r < 200) & (g > 30) & (g < 140) & (b < 100) & (r > g + 12)
    lab, n = ndimage.label(ndimage.binary_dilation(shoe, iterations=2))
    out = []
    for i in range(1, n + 1):
        m = (lab == i) & shoe
        if m.sum() < 60: continue
        yy, xx = np.nonzero(m)
        # the sole: lowest rows of the blob; its x = centre of those rows
        low = yy >= yy.max() - 6
        out.append({'x': float(xx[low].mean() - ax), 'y': float(yy.max() - ay), 'n': int(m.sum())})
    out.sort(key=lambda s: -s['n'])
    return out[:2]


def track(name):
    A = ANIMS[name]
    im = Image.open(ROOT / 'assets' / (A['src'] + '.png')).convert('RGBA')
    k = A['k']
    F = []
    for (x, y, w, h, ax, ay) in A['frames']:
        F.append(shoes(im.crop((x, y, x + w, y + h)), ax, ay))
    n = len(F)
    # In units. A shoe is on the ground when its sole is within 5 units of the ground line. The stance foot starts as the
    # front foot of frame 0 (a contact pose); each frame it is the grounded shoe nearest to where it should be (a little
    # further back); when a new foot lands far in front while the stance foot is far back, the new one takes over.
    G = [[{'x': sh['x'] * k, 'y': sh['y'] * k} for sh in f] for f in F]
    grounded = lambda f: [sh for sh in f if sh['y'] > -5]
    stance = min(grounded(G[0]), key=lambda sh: sh['x'])['x']
    adv = []
    for i in range(n):
        nxt = grounded(G[(i + 1) % n])
        cand = [sh for sh in nxt if sh['x'] >= stance - 6]
        if not cand:
            adv.append(0.0); continue
        new = min(cand, key=lambda sh: abs(sh['x'] - (stance + 8)))['x']
        adv.append(max(0.0, new - stance))
        stance = new
        front = [sh for sh in nxt if sh['x'] < stance - 25]
        if front and stance > 15:
            stance = min(front, key=lambda sh: sh['x'])['x']
    adv = np.array(adv)
    # keep the foot lock; a single jump above CAP units is spread half-and-half onto its neighbours (a lurch, not a hop)
    CAP = 16.0
    sm = adv.copy()
    for i in range(n):
        if sm[i] > CAP:
            ex = sm[i] - CAP; sm[i] = CAP; sm[i - 1] += ex / 2; sm[(i + 1) % n] += ex / 2
    G = np.concatenate([[0], np.cumsum(sm)])
    A['ground'] = [round(float(v), 2) for v in G]
    # check plot: per-frame advance
    W_, H_ = 640, 220
    pl = Image.new('RGB', (W_, H_), (25, 25, 25)); d = ImageDraw.Draw(pl)
    mx = max(adv.max(), 1e-6)
    for i, (v, s) in enumerate(zip(adv, sm)):
        x = 10 + i * (W_ - 20) / n
        d.rectangle([x, H_ - 20 - v / mx * 170, x + 8, H_ - 20], fill=(90, 160, 255))
        d.rectangle([x + 9, H_ - 20 - s / mx * 170, x + 15, H_ - 20], fill=(255, 200, 60))
        d.text((x, H_ - 16), str(i), fill=(200, 200, 200))
    d.text((10, 6), f'{name}: cycle {G[-1]:.1f} units, per-frame advance (blue raw, yellow smoothed)', fill=(255, 255, 255))
    pl.save(ROOT / 'render' / 'review' / f'footlock_{name}.png')
    print(name, 'cycle', round(float(G[-1]), 1), 'units; advance', ' '.join(f'{v:.1f}' for v in adv))


names = sys.argv[1:] or ['zwalk12']
for nm in names: track(nm)
# edited copies of a walk (same poses) use its track
for nm, frm in {'zwalk12_head': 'zwalk12'}.items():
    if nm in ANIMS and 'ground' in ANIMS.get(frm, {}): ANIMS[nm]['ground'] = ANIMS[frm]['ground']
AP.write_text('// generated by tools/build.py (+ ground tracks from tools/footlock.py)\nwindow.ANIMS = ' + json.dumps(ANIMS) + ';\n', encoding='utf-8')
